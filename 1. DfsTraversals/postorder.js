/*************** RECURSIVE SOLUTION ***************/
var postorderTraversal = function(root) {
    if(!root) return [];
    
    const postorderLeft = postorderTraversal(root.left);
    const postorderRight = postorderTraversal(root.right);

    return [...postorderLeft, ...postorderRight, root.val];
}

/************* Iterative solution using 2 stacks ***********/
var postorderTraversal = function(root) {
    const stack = [root], postOrder = [];

    if(!root)
        return postOrder;

    while(stack.length) {
        const currentNode = stack.pop();
        postOrder.push(currentNode.val);

        if(currentNode.left) 
            stack.push(currentNode.left);
        if(currentNode.right) 
            stack.push(currentNode.right);
    }

    return postOrder.reverse();
};

